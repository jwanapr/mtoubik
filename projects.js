// ==========================================
// GET PROJECT
// ==========================================

const params = new URLSearchParams(window.location.search);

const projectID = params.get("project") || "zid";

const project = projects[projectID] || projects.zid;


// ==========================================
// INSERT DATA
// ==========================================

document.title = `${project.title} | أعمالنا`;

document.getElementById("projectTitle").textContent =
  project.title;

document.getElementById("breadcrumbTitle").textContent =
  project.title;

document.getElementById("projectCategory").textContent =
  project.category;

document.getElementById("projectIntro").textContent =
  project.intro;

const heroImage = document.getElementById("heroImage");
heroImage.src = project.image;
heroImage.addEventListener("error", () => {
  const fallback = project.image.replace(".webp", ".png");
  if (!heroImage.src.endsWith(fallback)) heroImage.src = fallback;
}, { once: true });

heroImage.alt = project.title;

document.getElementById("aboutText").textContent =
  project.about;

document.getElementById("goalText").textContent =
  project.goal;

document.getElementById("executionText").textContent =
  project.execution;

document.getElementById("resultText").textContent =
  project.result;

document.getElementById("typeText").textContent =
  project.type;

document.getElementById("serviceText").textContent =
  project.service;

document.getElementById("platformText").textContent =
  project.platform;


// ==========================================
// MORE PROJECTS
// ==========================================

const moreProjects =
  document.getElementById("moreProjects");

Object.entries(projects)
  .filter(([id]) => id !== projectID)
  .slice(0, 3)
  .forEach(([id, item]) => {

    moreProjects.insertAdjacentHTML(
      "beforeend",

      `
      <div class="col-md-4">

        <a
          href="project.html?project=${id}"
          class="more-card"
        >

          <div class="more-card-image">

            <img
              src="${item.image}"
              alt="${item.title}"
              loading="lazy"
            >

          </div>

          <div class="more-card-title">
            ${item.title}
          </div>

          <div class="more-card-type">
            ${item.category}
          </div>

        </a>

      </div>
      `
    );

  });



